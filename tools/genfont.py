# ---------------------------------------------------------------------------
# qito-mono - the terminal face
#
# Starts from qito-sans and overrides the glyphs where a terminal wants
# something different: unambiguous lookalikes and squarer, more even shapes.
# ---------------------------------------------------------------------------

MONO: dict[str, str] = dict(SANS)


def mono(char: str, *rows: str) -> None:
    art = list(rows)
    while len(art) < ART_H:
        art.append("." * CELL_W)
    for index, row in enumerate(art):
        assert len(row) == CELL_W, f"mono {char!r} row {index} is {len(row)} wide"
    MONO[char] = "/".join(art)


# A slashed zero, so it cannot be read as a capital O.
mono("0", _, _, "..####..", ".##..##.", "##...###", "##..####", "####..##",
     "###...##", ".##..##.", "..####..", _, _, _, _)
# A serifed one, distinct from lowercase l and capital I.
mono("1", _, _, "...##...", "..###...", ".####...", "...##...", "...##...",
     "...##...", "...##...", ".######.", _, _, _, _)
# Capital I keeps its crossbars; lowercase l gains a tail.
mono("l", _, "..###...", "....##..", "....##..", "....##..", "....##..",
     "....##..", "....##..", "##..##..", ".####...", _, _, _, _)
# A dotted, narrower lowercase i.
mono("i", _, "...##...", "...##...", _, "..###...", "...##...", "...##...",
     "...##...", "...##...", ".######.", _, _, _, _)
# Squarer parentheses and braces read better in code.
