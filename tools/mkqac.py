#!/usr/bin/env python3
"""
mkqac.py - build Qira Application iCon (.qac) files.

Icons are authored as ASCII art with a colour key, which keeps them
reviewable in source control, and are emitted at several sizes in a single
file. Three encodings are tried per frame and the smallest is kept, so a .qac
is never larger than the raw pixels it represents.

See src/kernel/include/kernel/qac.h for the on-disk layout.

Usage:
    mkqac.py --builtin --output-dir rootfs/usr/share/icons
    mkqac.py --art terminal.txt --name terminal --output terminal.qac
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

MAGIC = b"QACI"
VERSION = 1
HEADER_FMT = "<4sHHII I12s"
HEADER_FMT = "<4sHHIII12s"
HEADER_SIZE = struct.calcsize(HEADER_FMT)
ENTRY_FMT = "<HHBBHII"
ENTRY_SIZE = struct.calcsize(ENTRY_FMT)

QAC_RAW, QAC_RLE, QAC_INDEX = 0, 1, 2

assert HEADER_SIZE == 32, HEADER_SIZE
assert ENTRY_SIZE == 16, ENTRY_SIZE


# --- encoding --------------------------------------------------------------


def encode_raw(pixels: list[int]) -> bytes:
    out = bytearray()
    for pixel in pixels:
        out += bytes(
            [pixel & 0xFF, (pixel >> 8) & 0xFF, (pixel >> 16) & 0xFF, pixel >> 24]
        )
    return bytes(out)


def encode_rle(pixels: list[int]) -> bytes:
    out = bytearray()
    index = 0

    while index < len(pixels):
        pixel = pixels[index]
        run = 1
        while (
            index + run < len(pixels)
            and pixels[index + run] == pixel
            and run < 255
        ):
            run += 1
        out += bytes(
            [run, pixel & 0xFF, (pixel >> 8) & 0xFF, (pixel >> 16) & 0xFF, pixel >> 24]
        )
        index += run

    return bytes(out)


def encode_indexed(pixels: list[int]) -> tuple[bytes, int] | None:
    """Palette encoding, or None when the image needs more than 256 colours."""
    palette: list[int] = []
    lookup: dict[int, int] = {}

    for pixel in pixels:
        if pixel not in lookup:
            if len(palette) >= 256:
                return None
            lookup[pixel] = len(palette)
            palette.append(pixel)

    out = bytearray()
    for colour in palette:
        out += bytes(
            [
                colour & 0xFF,
                (colour >> 8) & 0xFF,
                (colour >> 16) & 0xFF,
                colour >> 24,
            ]
        )
    for pixel in pixels:
        out.append(lookup[pixel])

    return bytes(out), len(palette)


def best_encoding(pixels: list[int]) -> tuple[int, bytes, int]:
    """Return (encoding, data, palette_size) for the smallest representation."""
    candidates: list[tuple[int, int, bytes, int]] = []

    raw = encode_raw(pixels)
    candidates.append((len(raw), QAC_RAW, raw, 0))

    rle = encode_rle(pixels)
    candidates.append((len(rle), QAC_RLE, rle, 0))

    indexed = encode_indexed(pixels)
    if indexed is not None:
        data, palette_size = indexed
        # A palette of 256 is stored as 0 in a byte field.
        candidates.append(
            (len(data), QAC_INDEX, data, palette_size % 256)
        )

    candidates.sort(key=lambda item: item[0])
    _size, encoding, data, palette_size = candidates[0]
    return encoding, data, palette_size


# --- scaling ---------------------------------------------------------------


def scale(pixels: list[int], src: int, dst: int) -> list[int]:
    """Box-filter an icon down, or nearest-neighbour it up."""
    if src == dst:
        return list(pixels)

    out = []
    if dst < src:
        factor = src / dst
        for y in range(dst):
            for x in range(dst):
                x0, x1 = int(x * factor), max(int((x + 1) * factor), int(x * factor) + 1)
                y0, y1 = int(y * factor), max(int((y + 1) * factor), int(y * factor) + 1)

                a = r = g = b = count = 0
                for sy in range(y0, min(y1, src)):
                    for sx in range(x0, min(x1, src)):
                        pixel = pixels[sy * src + sx]
                        pa = pixel >> 24
                        # Weight colour by alpha so transparent pixels do not
                        # drag the edges toward black.
                        a += pa
                        r += ((pixel >> 16) & 0xFF) * pa
                        g += ((pixel >> 8) & 0xFF) * pa
                        b += (pixel & 0xFF) * pa
                        count += 1

                if count == 0 or a == 0:
                    out.append(0)
                else:
                    out.append(
                        ((a // count) << 24)
                        | ((r // a) << 16)
                        | ((g // a) << 8)
                        | (b // a)
                    )
    else:
        for y in range(dst):
            for x in range(dst):
                out.append(pixels[(y * src // dst) * src + (x * src // dst)])

    return out


# --- file assembly ---------------------------------------------------------


def build(frames: dict[int, list[int]], name: str) -> bytes:
    sizes = sorted(frames.keys(), reverse=True)

    entries = bytearray()
    payload = bytearray()

    for size in sizes:
        encoding, data, palette_size = best_encoding(frames[size])
        entries += struct.pack(
            ENTRY_FMT, size, size, encoding, palette_size, 0, len(payload), len(data)
        )
        payload += data

    checksum = sum(payload) & 0xFFFFFFFF

    header = struct.pack(
        HEADER_FMT,
        MAGIC,
        VERSION,
        len(sizes),
        len(payload),
        checksum,
        0,
        name.encode("ascii", "ignore")[:12],
    )

    return bytes(header + entries + payload)


