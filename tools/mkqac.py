def art_to_pixels(rows: list[str], palette: dict[str, int]) -> list[int]:
    pixels = []
    for row in rows:
        for char in row:
            if char not in palette:
                raise SystemExit(f"error: unknown colour key {char!r}")
            pixels.append(palette[char])
    return pixels


def load_art_file(path: str) -> list[str]:
    with open(path) as handle:
        rows = [line.rstrip("\n") for line in handle if line.strip()]
    if len(rows) != 32:
        raise SystemExit(f"error: {path} has {len(rows)} rows, expected 32")
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description="Build .qac icon files")
    parser.add_argument("--builtin", action="store_true",
                        help="emit every built-in icon")
    parser.add_argument("--output-dir", default=None)
    parser.add_argument("--art", default=None, help="a 32x32 ASCII art file")
    parser.add_argument("--name", default="icon")
    parser.add_argument("--output", default=None)
    parser.add_argument("--sizes", default="32,24,16",
                        help="comma separated frame sizes")
    args = parser.parse_args()

    sizes = [int(value) for value in args.sizes.split(",")]

    if args.builtin:
        if not args.output_dir:
            raise SystemExit("error: --builtin needs --output-dir")
        os.makedirs(args.output_dir, exist_ok=True)

        total = 0
        for name, rows in sorted(ICONS.items()):
            pixels = art_to_pixels(rows, PALETTE)
            frames = {size: scale(pixels, 32, size) for size in sizes}
            data = build(frames, name)

            path = os.path.join(args.output_dir, f"{name}.qac")
            with open(path, "wb") as handle:
                handle.write(data)

            raw_size = 32 * 32 * 4
            print(f"  {name:12s} {len(data):6d} bytes  "
                  f"({len(sizes)} frames, {raw_size // max(len(data), 1)}x smaller "
                  f"than one raw 32x32 frame)")
            total += len(data)

        print(f"{len(ICONS)} icons, {total} bytes total")
        return 0

    if args.art:
        rows = load_art_file(args.art)
        pixels = art_to_pixels(rows, PALETTE)
        frames = {size: scale(pixels, 32, size) for size in sizes}
        data = build(frames, args.name)

        output = args.output or f"{args.name}.qac"
        with open(output, "wb") as handle:
            handle.write(data)
        print(f"wrote {output} ({len(data)} bytes)")
        return 0

    parser.print_help()
    return 1


